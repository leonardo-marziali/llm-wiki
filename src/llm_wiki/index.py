"""Generate section ``_index.md`` files and the top-level ``index.md``."""

from pathlib import Path

from llm_wiki.config import WikiConfig
from llm_wiki.pages import Page, iter_pages

GENERATED_MARK = "<!-- generated by wiki: do not edit below -->"
MAX_TOP_LINES = 99  # index.md must stay under 100 lines
TRUNCATED = "- … see section indexes"


def _one_line(text: str) -> str:
    return " ".join(text.split())


def _link_title(text: str) -> str:
    return _one_line(text).replace("[", r"\[").replace("]", r"\]")


def _sort_key(page: Page) -> tuple[bool, str, str]:
    assert page.fm is not None
    return (page.fm.type != "hub", page.fm.title.casefold(), page.rel)


def _header(path: Path, default: str) -> str:
    if path.is_file():
        text = path.read_text(encoding="utf-8")
        if GENERATED_MARK in text:
            return text.split(GENERATED_MARK, 1)[0]
        return text.rstrip("\n") + "\n\n"
    return default


def _write_if_changed(path: Path, header: str, lines: list[str]) -> bool:
    content = header + GENERATED_MARK + "\n" + "".join(f"{ln}\n" for ln in lines)
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def _section_lines(pages: list[Page], section: str) -> list[str]:
    lines = []
    for p in sorted(pages, key=_sort_key):
        fm = p.fm
        assert fm is not None
        link = p.rel.removeprefix(section + "/")
        lines.append(f"- [{_link_title(fm.title)}]({link}) — {_one_line(fm.summary)} — {fm.status} — {fm.last_verified.isoformat()}")
    return lines


def build_indexes(root: Path, cfg: WikiConfig) -> list[Path]:
    """Write all index files; return those whose content changed."""
    wiki = root / "wiki"
    by_section: dict[str, list[Page]] = {s.name: [] for s in cfg.sections}
    for page in iter_pages(root):
        if page.fm is None or "/" not in page.rel:
            continue
        section = page.rel.split("/", 1)[0]
        if section in by_section:
            by_section[section].append(page)

    changed: list[Path] = []
    for s in cfg.sections:
        path = wiki / s.name / "_index.md"
        default = f"# {s.name[:1].upper()}{s.name[1:]}\n\n{s.description}\n\n"
        if _write_if_changed(path, _header(path, default), _section_lines(by_section[s.name], s.name)):
            changed.append(path)

    top = wiki / "index.md"
    lines = [
        "- [Overview](overview.md)",
        "- [Glossary](glossary.md)",
        "- [Open questions](open-questions.md)",
        "",
        "## Sections",
        "",
    ]
    for s in cfg.sections:
        lines.append(f"- [{s.name}]({s.name}/_index.md) — {len(by_section[s.name])} pages — {s.description}")
    lines += ["", "## Hubs", ""]
    hubs = sorted(
        (p for pages in by_section.values() for p in pages if p.fm and p.fm.type == "hub"),
        key=lambda p: (p.fm.title.casefold(), p.rel),  # type: ignore[union-attr]
    )
    hub_lines = [f"- [{_link_title(p.fm.title)}]({p.rel})" for p in hubs]  # type: ignore[union-attr]
    header = _header(top, f"# {cfg.name}\n\n{cfg.description}\n\n")
    budget = MAX_TOP_LINES - header.count("\n") - 1 - len(lines)
    if len(hub_lines) > budget:
        hub_lines = hub_lines[: budget - 1] + [TRUNCATED] if budget >= 1 else []
    if _write_if_changed(top, header, lines + hub_lines):
        changed.append(top)
    return changed
